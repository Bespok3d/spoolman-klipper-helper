"""Fakes for the Klipper host objects a test needs to drive the REAL plugin code.

Every test that exercises the real `Spoolman` needs the same four stand-ins (a reactor whose
timers a test drains by hand, a webhooks that records the Moonraker calls, a printer that hands
those out, and a log sink). They lived in one test file and were about to be copied into a
third, so they live here once.
"""
from spoolman.helper_options import HelperOptions


class WrittenSection:
    """The [spoolman_helper] section with only the options a test wrote in it."""

    def __init__(self, written):
        self.written = written

    def get(self, key, default=None):
        return self.written.get(key, default)


def helper_options(**written):
    """The options a printer would read, with the given ones turned over and the rest shipped."""
    return HelperOptions(WrittenSection(written))


class FakeReactor:
    NEVER = 9e99

    def __init__(self):
        self.timers = []

    def monotonic(self):
        return 0.0

    def register_timer(self, callback, when):
        self.timers.append((callback, when))


class RecordingGcode:
    def __init__(self):
        self.commands = {}
        self.responses = []

    def register_command(self, name, handler, desc=""):
        self.commands[name] = handler

    def respond_info(self, message):
        self.responses.append(message)


class RecordingWebhooks:
    def __init__(self, printer):
        self.printer = printer
        self.endpoints = {}
        self.remote_calls = []

    def register_endpoint(self, path, handler):
        self.endpoints[path] = handler

    def call_remote_method(self, method, **params):
        self.remote_calls.append((method, params))


class FakePrinter:
    def __init__(self):
        self.reactor = FakeReactor()
        self.objects = {"gcode": RecordingGcode()}
        self.objects["webhooks"] = RecordingWebhooks(self)

    def lookup_object(self, name, default=KeyError):
        if name in self.objects:
            return self.objects[name]
        if default is KeyError:
            raise KeyError(name)
        return default

    def get_reactor(self):
        return self.reactor


class RecordingLogs:
    def __init__(self):
        self.lines = []
        self.debug_lines = []

    def _record(self, message):
        self.lines.append(message)

    def debug(self, message):
        self.debug_lines.append(message)
        self._record(message)

    log = warn = error = verbose = _record


def drain_timers(reactor):
    while reactor.timers:
        callback, _when = reactor.timers.pop(0)
        callback(0.0)


class FakePrintStats:
    def __init__(self, state):
        self.state = state


class FakeSdcard:
    def __init__(self, gcode_path):
        self.gcode_path = gcode_path

    def file_path(self):
        return self.gcode_path


class FakePrintTaskConfig:
    def __init__(self, config):
        self.print_task_config = config


# A remapped print: T0>E2, T1>E0, T5>E2. The firmware fills the whole table; every entry the
# file never set still reads as lane 0, and the file's header names the tools it uses.
REMAPPED_TABLE = [2, 0, 0, 0, 0, 2]
REMAPPED_HEADER = "; generated by a slicer\n; filament: 1,2,6\nG28\n"


def write_remapped_gcode(folder):
    """Saves the remapped print's file in this folder and gives back its path."""
    gcode_path = folder / "remapped.gcode"
    gcode_path.write_text(REMAPPED_HEADER)
    return str(gcode_path)
